"""Check that every feature in src/content/features.json appears on at least one page,
and that pages only reference features that exist. Also writes content/09-features.md.

Run: python3 -I scripts/check-features.py
"""
import json
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent
catalogue = json.loads((root / "src/content/features.json").read_text())["features"]

# Map each feature id to the routes that show it.
used: dict[str, list[str]] = {fid: [] for fid in catalogue}
unknown: list[tuple[str, str]] = []
built_routes = {
    "clinicalFeatures": "/products/clinical",
    "minorAilmentsFeatures": "/products/clinical/minor-ailments",
    "incidentReportingFeatures": "/products/assure/incident-reporting",
    "independentPharmaciesFeatures": "/solutions/independent-pharmacies",
}

def record(route: str, text: str) -> None:
    for ids in re.findall(r'"ids":\s*\[([^\]]*)\]', text):
        for fid in re.findall(r'"([A-Za-z0-9]+)"', ids):
            if fid in used:
                if route not in used[fid]:
                    used[fid].append(route)
            else:
                unknown.append((route, fid))

for path in sorted((root / "src/content/pages").glob("*.ts")):
    text = path.read_text()
    starts = [(m.start(), m.group(1)) for m in re.finditer(r'\n  "(/[^"]*)": \{', text)]
    for index, (start, route) in enumerate(starts):
        end = starts[index + 1][0] if index + 1 < len(starts) else len(text)
        record(route, text[start:end])

sections = (root / "src/content/featureSections.ts").read_text()
for name, route in built_routes.items():
    match = re.search(rf"export const {name}[^=]*= (\{{.*?\}});\n", sections, re.S)
    if match:
        record(route, match.group(1))

missing = [fid for fid, routes in used.items() if not routes]

lines = ["# Feature inventory", "", "Generated by `scripts/check-features.py` from `src/content/features.json`. Every feature below is described on the website; the last column shows where.", ""]
for product in dict.fromkeys(f["product"] for f in catalogue.values()):
    lines += [f"## {product}", "", "| Feature | Description | Source | Pages |", "|---|---|---|---|"]
    for fid, feature in catalogue.items():
        if feature["product"] != product:
            continue
        pages = ", ".join(f"`{r}`" for r in used[fid]) or "**not on any page**"
        lines.append(f"| {feature['title']} | {feature['text']} | {feature['source']} | {pages} |")
    lines.append("")
lines += ["Source codes: OLD = zeenovo.com, STG = staging build, ENT = Enterprise Module proposal, DES = approved design, DUMMY = placeholder.", ""]
(root / "content/09-features.md").write_text("\n".join(lines))

print(f"{len(catalogue)} features, {len(catalogue) - len(missing)} on the site")
for fid in missing:
    print(f"MISSING: {fid} ({catalogue[fid]['title']})")
for route, fid in unknown:
    print(f"UNKNOWN: {fid} referenced on {route}")
sys.exit(1 if missing or unknown else 0)
