"""Turn the Figma line-art exports into inline markup for <LineArt />.

Each visible stroke is written twice: a static copy (class "la-base", shown faint behind) and the animated line
(class "la-line") with pathLength="100", so its dash pattern is a share of that line's own length, and its own phase
(--d, a fraction of the cycle), so the travelling gap starts at a different point on every line.
Page-sized backing rectangles from the Figma export are dropped. Run from the repo root:
    python scripts/generate-line-art.py
"""
import re

SOURCES = [
    ("public/assets/figma-values-wave.svg", "src/components/lineArt/valuesWave.ts", "valuesWave", "vw"),
    ("public/assets/figma-philosophy-lines.svg", "src/components/lineArt/philosophyLines.ts", "philosophyLines", "ph"),
    ("public/assets/independent-pharmacies-change-art.svg", "src/components/lineArt/changeWave.ts", "changeWave", "cw"),
]

for source, target, name, prefix in SOURCES:
    svg = open(source, encoding="utf-8").read()
    svg = re.sub(r'<rect width="1440" height="[\d.]+"[^>]*fill="(?:#E5E5E5|white|none)"/>\s*', "", svg)
    svg = svg.replace("_69_5452", f"_{prefix}")

    def mark(match):
        nonlocal_count[0] += 1
        delay = (nonlocal_count[0] * 0.618034) % 1  # golden-ratio spread: neighbouring lines never move in step
        tag = re.sub(r' id="[^"]*"', "", match.group(0))
        base = tag.replace("<path ", '<path class="la-base" ')
        return base + tag.replace("<path ", f'<path class="la-line" pathLength="100" style="--d:{delay:.3f}" ')

    nonlocal_count = [0]
    svg = re.sub(r'<path id="[^"]*" d="[^"]*" stroke="[^"]*" stroke-width="[^"]*"/>', mark, svg)
    svg = re.sub(r' id="(?!mask|clip)[^"]*"', "", svg)
    width, height = re.search(r'<svg width="([\d.]+)" height="([\d.]+)"', svg).groups()
    inner = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1)
    inner = re.sub(r">\s+<", "><", inner).strip()
    with open(target, "w", encoding="utf-8") as out:
        out.write(f"// Generated by scripts/generate-line-art.py from {source}. Do not edit by hand.\n")
        out.write(f"export const {name} = {{ width: {width}, height: {height}, markup: `{inner}` }};\n")
    print(target, len(inner))
